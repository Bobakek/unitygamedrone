import { makeName } from '../galaxy/names.ts';
import { Rng } from '../math/rng.ts';
import type { SiteDef } from './sites.ts';

/** The ship's log on a wreck's bridge: who they were and how it ended (deterministic per wreck). */
export function wreckLog(s: SiteDef, planet: string): { title: string; entries: string[] } {
  const r = new Rng(s.seed ^ 0x10c);
  const ship = s.name.replace(/^Разбитый\s*/, '').replace(/[«»]/g, '');
  const cls = r.pick(['грузовой корабль', 'рудовоз', 'исследовательское судно', 'курьер Гильдии', 'транспорт колонистов', 'патрульный корвет']);
  const captain = `${r.pick(['Капитан', 'Капитан', 'Старший пилот', 'Командир'])} ${makeName(r)}`;
  const day = r.int(40, 380);
  const cause = r.pick([
    ['Пираты Синдиката висят на хвосте третьи сутки. Щиты на нуле.', 'Прямое попадание в машинное. Тянем к поверхности — другого выхода нет.'],
    ['Реактор пошёл вразнос после прыжка. Охлаждение не справляется.', 'Глушим всё, что можно. Садимся на ' + planet + ', пока держит корпус.'],
    ['Навигация сбоит с самой станции. Похоже, кто-то покопался в прошивке.', 'Мы не туда вышли из прыжка. Атмосфера плотнее расчётной.'],
    ['Пойман сигнал бедствия с поверхности. Снижаемся проверить.', 'Это не сигнал бедствия. Это маяк-приманка. Двигатели не отвечают.'],
    ['Метеоритный поток прошил трюм. Разгерметизация в двух отсеках.', 'Пытаемся сесть на брюхо. Пристегнитесь.'],
  ]);
  const after = r.pick([
    'Экипаж ушёл к ближайшей станции на спасательной капсуле. Груз остаётся в трюме — кто найдёт, пусть заберёт.',
    'Дроны охраны переведены в автономный режим. Они не отличат своих от чужих — не подходите без нужды.',
    'Реактор фонит. Кто полезет в машинное — наденьте радиационный экран.',
    'Ценный груз спрятан в каюте капитана и в трюме. Шифр знаем только мы.',
  ]);
  return {
    title: `Бортовой журнал: «${ship}», ${cls}`,
    entries: [
      `День ${day}. ${captain}. Вышли с грузом реликтов и кристаллов, курс — станция системы.`,
      `День ${day + 1}. ${cause[0]}`,
      `День ${day + 1}, позже. ${cause[1]}`,
      `День ${day + 2}. Сели жёстко. ${after}`,
    ],
  };
}
